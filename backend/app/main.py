"""FastAPI application factory.

Routers are discovered, not registered by hand: every module in
``app.api.routers`` that exports ``router: APIRouter`` is included under
``/api/v1``. A module may also export ``root_router: APIRouter`` for the few
endpoints that live outside the versioned prefix (``/healthz``, ``/readyz``).
Do not edit this file to add a router.
"""

from __future__ import annotations

import importlib
import pkgutil
import secrets
from collections.abc import AsyncIterator
from contextlib import asynccontextmanager
from types import ModuleType

from fastapi import APIRouter, FastAPI

from app import __version__
from app.api import routers as routers_package
from app.auth.sessions import session_id_from_cookie
from app.core.csrf import CSRFProtect, install_csrf
from app.core.errors import UnhandledErrorMiddleware, install_error_handlers
from app.core.headers import SecurityHeadersMiddleware
from app.core.limits import DEFAULT_MAX_BODY_BYTES, BodySizeLimitMiddleware
from app.core.metrics import MetricsMiddleware
from app.core.request_context import RequestContextMiddleware
from app.core.settings import Settings, get_settings
from app.core.spa import install_spa
from app.db.session import make_app_engine, make_sessionmaker

API_PREFIX = "/api/v1"


def discover_routers(package: ModuleType) -> list[tuple[str, APIRouter | None, APIRouter | None]]:
    """Import every public module in ``package``; return ``(name, router, root_router)``."""
    found: list[tuple[str, APIRouter | None, APIRouter | None]] = []
    for info in sorted(pkgutil.iter_modules(package.__path__), key=lambda i: i.name):
        if info.name.startswith("_"):
            continue
        module = importlib.import_module(f"{package.__name__}.{info.name}")
        router = getattr(module, "router", None)
        root_router = getattr(module, "root_router", None)
        found.append(
            (
                info.name,
                router if isinstance(router, APIRouter) else None,
                root_router if isinstance(root_router, APIRouter) else None,
            )
        )
    return found


def include_routers(app: FastAPI, package: ModuleType = routers_package) -> list[str]:
    """Include discovered routers; return the module names that contributed one."""
    included: list[str] = []
    for name, router, root_router in discover_routers(package):
        if router is not None:
            app.include_router(router, prefix=API_PREFIX)
        if root_router is not None:
            app.include_router(root_router)
        if router is not None or root_router is not None:
            included.append(name)
    return included


UPLOAD_PATHS = (f"{API_PREFIX}/documents",)


def _csrf_key(settings: Settings) -> bytes:
    """``PERFIN_SECRET_KEY``, or a per-process random key when unset.

    A missing secret key is refused outside dev mode by ``perfin config
    check``; the random fallback only means tokens do not survive a restart.
    """
    if settings.secret_key is not None:
        return settings.secret_key.get_secret_value().encode("utf-8")
    return secrets.token_bytes(32)


def _install_middleware(app: FastAPI, settings: Settings) -> None:
    """Install error handlers and the middleware stack.

    ``add_middleware`` wraps, so each call below becomes the new outermost
    layer. Request order (outermost first):

    1. ``MetricsMiddleware``: count and time by route template.
    2. ``RequestContextMiddleware``: request id, client IP/scheme from
       trusted proxies only.
    3. ``SecurityHeadersMiddleware``: CSP and security headers, ``no-store``.
    4. ``BodySizeLimitMiddleware``: 1 MiB, upload paths ``PERFIN_UPLOAD_MAX_MB``.
    5. ``CSRFMiddleware``: Origin/Sec-Fetch-Site and token on unsafe /api/v1.
    6. ``UnhandledErrorMiddleware``: any escaped exception becomes a generic
       500 problem (inside 2 and 3, so it still gets headers and an id).
    """
    install_error_handlers(app)
    app.add_middleware(UnhandledErrorMiddleware)
    install_csrf(
        app,
        CSRFProtect(
            secret_key=_csrf_key(settings),
            public_origin=settings.public_url,
            # CSRF tokens bind to the session cookie (A5); no DB access here.
            get_session_id=session_id_from_cookie,
        ),
        api_prefix=API_PREFIX,
    )
    body_limits = dict.fromkeys(UPLOAD_PATHS, settings.upload_max_bytes)
    app.state.body_limit_overrides = body_limits
    app.add_middleware(
        BodySizeLimitMiddleware, default_limit=DEFAULT_MAX_BODY_BYTES, overrides=body_limits
    )
    app.add_middleware(
        SecurityHeadersMiddleware,
        hsts=not settings.dev_mode,
        trusted_types=settings.csp_trusted_types,
    )
    app.add_middleware(RequestContextMiddleware, trusted_proxies=settings.trusted_proxies)
    app.add_middleware(MetricsMiddleware)


def _refuse_insecure_config(settings: Settings) -> None:
    from app.core.config_check import InsecureConfigError, check_config, has_errors

    findings = check_config(settings)
    if has_errors(findings):
        raise InsecureConfigError(findings)


@asynccontextmanager
async def _lifespan(app: FastAPI) -> AsyncIterator[None]:
    try:
        yield
    finally:
        app.state.engine.dispose()


def create_app(settings: Settings | None = None) -> FastAPI:
    """Build the API application. ``settings`` defaults to ``get_settings()``.

    Without explicit ``settings`` (the ``uvicorn app.main:create_app
    --factory`` path, which is also how ``perfin api`` serves) the startup
    gate runs here too (SECURITY.md H6): outside dev mode an insecure
    configuration raises ``InsecureConfigError`` instead of serving. The
    ``perfin`` CLI has already logged each finding by then; run ``perfin
    config check`` to see them. Callers passing ``settings`` (tests, ``perfin
    openapi``) build the app without the gate.
    """
    if settings is None:
        settings = get_settings()
        _refuse_insecure_config(settings)
    app = FastAPI(
        title="PerFin",
        version=__version__,
        openapi_url=f"{API_PREFIX}/openapi.json" if settings.dev_mode else None,
        docs_url=f"{API_PREFIX}/docs" if settings.dev_mode else None,
        redoc_url=None,
        swagger_ui_oauth2_redirect_url=None,
        lifespan=_lifespan,
    )
    app.state.settings = settings
    engine = make_app_engine(settings)
    app.state.engine = engine
    app.state.sessionmaker = make_sessionmaker(engine)
    _install_middleware(app, settings)
    include_routers(app)
    # Last: the SPA fallback only answers what no router matched.
    install_spa(app, settings.static_dir)
    return app
