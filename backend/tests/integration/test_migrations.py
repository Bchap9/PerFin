def _head() -> str:
    head = ScriptDirectory.from_config(alembic_config()).get_current_head()
    assert head is not None
    return head


@dataclass(frozen=True)
class Scratch:
    """A fresh, empty database plus its owner and application roles."""

    database: str
    owner_url: URL
    app_url: URL
    app_role: str

    def config(self) -> Config:
        cfg = alembic_config()
        cfg.set_main_option(
            "sqlalchemy.url",
            self.owner_url.render_as_string(hide_password=False).replace("%", "%%"),
        )
        cfg.attributes["perfin_app_role"] = self.app_role
        return cfg

    def owner_engine(self) -> Engine:
        return make_engine(
            self.owner_url.render_as_string(hide_password=False), poolclass=pool.NullPool
        )

    def app_engine(self) -> Engine:
        return make_engine(
            self.app_url.render_as_string(hide_password=False), poolclass=pool.NullPool
        )


def _dsn(url: URL) -> str:
    return url.set(drivername="postgresql").render_as_string(hide_password=False)


