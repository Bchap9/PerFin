"""Alembic revisions on a fresh database (docs/DEVELOPMENT.md, "Migrations").

Each scratch database is created empty on the test server with a
non-superuser owner role that owns ``public`` (as ``deploy/db-init`` does for
``perfin_owner``) and a separate non-owner application role. The migrations
run as the owner, exactly like ``perfin migrate`` in production, and then:

* ``alembic check`` reports no drift between the models and the database;
* every ``HouseholdScoped`` table has row-level security enabled and forced;
* the application role can append to ``audit_log`` but never UPDATE, DELETE
  or TRUNCATE it, and the owner cannot either (trigger);
* the application role can read ``alembic_version`` (``/readyz``);
* ``downgrade base`` removes every table, function and enum type it created,
  and the database can be upgraded again.
"""

