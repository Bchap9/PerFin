def test_app_role_cannot_update_delete_or_truncate_audit_log(migrated: Scratch) -> None:
    app = migrated.app_engine()
    owner = migrated.owner_engine()
    household = uuid.uuid4()
    try:
        with app.begin() as conn:
            set_context(conn, household)
            conn.execute(
                text("INSERT INTO household (id, name) VALUES (:id, 'Synthetic household')"),
                {"id": household},
            )
        with app.begin() as conn:
            set_context(conn, household)
            audit(conn, action="test.append", target_type="household", household_id=household)
        for statement in (
            "UPDATE audit_log SET action = 'test.tampered'",
            "DELETE FROM audit_log",
            "TRUNCATE audit_log",
        ):
            with app.connect() as conn, conn.begin():
                set_context(conn, household)
                with pytest.raises(ProgrammingError) as excinfo:
                    conn.execute(text(statement))
            assert isinstance(excinfo.value.orig, psycopg.errors.InsufficientPrivilege)
            # The owner role is refused by the append-only trigger.
            with pytest.raises(DBAPIError) as refused, owner.begin() as conn:
                conn.execute(text(statement))
            assert "append-only" in str(refused.value.orig)
        with app.begin() as conn:
            set_context(conn, household)
            assert conn.execute(text("SELECT count(*) FROM audit_log")).scalar_one() == 1
        with owner.connect() as conn:
            result = verify_chain(conn)
        assert result.ok
        assert result.rows_checked == 1
    finally:
        app.dispose()
        owner.dispose()


def _count(conn: Connection, household: uuid.UUID, statement: str) -> int:
    set_context(conn, household)
    return int(conn.execute(text(statement), {"id": household}).scalar_one())


def test_household_rows_are_protected_from_other_households(migrated: Scratch) -> None:
    """Review finding SR-1, on a migrated database as the application role.

    Every household-scoped table references ``household`` ON DELETE CASCADE
    and referential actions ignore RLS, so deleting household A's row from
    household B's context would wipe A's (RLS-protected) rows. RLS on
    ``household`` makes both UPDATE and DELETE of another household no-ops.
    """
    app = migrated.app_engine()
    a, b = uuid.uuid4(), uuid.uuid4()
    try:
        for household, name in ((a, "Synthetic A"), (b, "Synthetic B")):
            with app.begin() as conn:
                set_context(conn, household)
                conn.execute(
                    text("INSERT INTO household (id, name) VALUES (:id, :name)"),
                    {"id": household, "name": name},
                )
                conn.execute(
                    text("INSERT INTO event (id, household_id, type) VALUES (:e, :id, 'test.x')"),
                    {"e": uuid.uuid4(), "id": household},
                )
        for context in (b, None):
            with app.begin() as conn:
                set_context(conn, context)
                renamed = conn.execute(
                    text("UPDATE household SET name = 'pwned' WHERE id = :id"), {"id": a}
                )
                deleted = conn.execute(text("DELETE FROM household WHERE id = :id"), {"id": a})
                assert (renamed.rowcount, deleted.rowcount) == (0, 0), context
                # Nor can another household's row be read.
                assert (
                    conn.execute(
                        text("SELECT count(*) FROM household WHERE id = :id"), {"id": a}
                    ).scalar_one()
                    == 0
                )
        with app.begin() as conn:
            assert _count(conn, a, "SELECT count(*) FROM event WHERE household_id = :id") == 1
            assert _count(conn, a, "SELECT count(*) FROM household WHERE name = 'pwned'") == 0
        # A household cannot be re-pointed or inserted for another id either.
        with app.begin() as conn:
            set_context(conn, b)
            with pytest.raises(DBAPIError, match="row-level security"):
                conn.execute(
                    text("INSERT INTO household (id, name) VALUES (:id, 'Forged')"),
                    {"id": uuid.uuid4()},
                )
        # In its own context a household can still be deleted, with its rows.
        with app.begin() as conn:
            set_context(conn, b)
            assert conn.execute(text("DELETE FROM household WHERE id = :id"), {"id": b}).rowcount
        with app.begin() as conn:
            assert _count(conn, b, "SELECT count(*) FROM event WHERE household_id = :id") == 0
            # Maintenance lists every household id without seeing other columns.
            set_context(conn, b)
            ids = set(conn.execute(text("SELECT * FROM perfin_household_ids()")).scalars())
            assert a in ids
            assert b not in ids
            # The function put the caller's (empty) instance-admin flag back.
            assert (
                conn.execute(
                    text("SELECT count(*) FROM household WHERE id = :id"), {"id": a}
                ).scalar_one()
                == 0
            )
    finally:
        app.dispose()


def test_app_role_privileges_are_least(migrated: Scratch) -> None:
    app = migrated.app_engine()
    try:
        with app.connect() as conn:
            # /readyz reads the revision as the application role.
            assert conn.execute(text("SELECT version_num FROM alembic_version")).scalar_one() == (
                _head()
            )
            privileges = {
                (str(r.table_name), str(r.privilege_type))
                for r in conn.execute(
                    text(
                        "SELECT table_name, privilege_type "
                        "FROM information_schema.role_table_grants "
                        "WHERE grantee = current_user AND table_schema = 'public'"
                    )
                )
            }
        with pytest.raises(ProgrammingError), app.begin() as conn:
            conn.execute(text("CREATE TABLE intruder (id int)"))
        with pytest.raises(ProgrammingError), app.begin() as conn:
            conn.execute(text("ALTER TABLE household ADD COLUMN x int"))
    finally:
        app.dispose()
    assert {p for t, p in privileges if t == "audit_log"} == {"SELECT", "INSERT"}
    assert {p for t, p in privileges if t == "alembic_version"} == {"SELECT"}
    for table in sorted((PHASE0_TABLES | PHASE1_TABLES) - {"audit_log"}):
        assert {p for t, p in privileges if t == table} == {
            "SELECT",
            "INSERT",
            "UPDATE",
            "DELETE",
        }, table


