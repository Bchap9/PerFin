def test_downgrade_base_removes_everything_and_upgrade_again(migrated: Scratch) -> None:
    cfg = migrated.config()
    command.downgrade(cfg, "base")
    engine = migrated.owner_engine()
    try:
        assert _public_tables(engine) == {"alembic_version"}
        with engine.connect() as conn:
            functions = set(
                conn.execute(
                    text("SELECT proname FROM pg_proc WHERE pronamespace = 'public'::regnamespace")
                ).scalars()
            )
            types = set(
                conn.execute(
                    text(
                        "SELECT typname FROM pg_type "
                        "WHERE typnamespace = 'public'::regnamespace AND typtype = 'e'"
                    )
                ).scalars()
            )
            version = conn.execute(text("SELECT count(*) FROM alembic_version")).scalar_one()
        assert functions == set()
        assert types == set()
        assert version == 0
        # The round trip is repeatable.
        command.upgrade(cfg, "head")
        command.check(cfg)
    finally:
        engine.dispose()


