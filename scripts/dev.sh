#
# Local development stack (`make dev`; docs/DEVELOPMENT.md, "Dev stack").
#
#   scripts/dev.sh [up]     start everything (default)
#   scripts/dev.sh seed     run only the seed (database must be up and migrated)
#   scripts/dev.sh down     stop the database container (data is kept)
#   scripts/dev.sh reset    delete the database volume and .dev/ (next `up` re-seeds)
#
# `up` does, in order:
#   1. generate .dev/env once (mode 0600): random database passwords, master
#      and secret keys. Nothing here is a default credential.
#   2. start PostgreSQL 16 (deploy/docker-compose.dev.yml, published on
#      127.0.0.1:$PERFIN_DEV_DB_PORT, default 55432) and wait until healthy
#   3. `uv sync`, `npm ci` (if node_modules is missing), `perfin migrate`
#   4. seed a synthetic household (scripts/seed_dev.py). It prints the dev
#      admin's generated password ONCE; a second `up` does not reseed.
#   5. run the API with --reload (127.0.0.1:8000), the worker and the Vite dev
#      server (http://localhost:5173, proxies /api) until Ctrl-C.
#
# Requirements: Docker with the compose plugin, uv, Node 22 + npm, openssl, Linux
# (the worker's extraction sandbox uses seccomp and Landlock).
# Behind a registry mirror: POSTGRES_IMAGE=mirror.gcr.io/library/postgres:16-alpine make dev
#
# PERFIN_DEV_MODE=true is set for every process: security checks are relaxed
# (plain-HTTP cookies, no MFA enrolment). Never put real data in this stack.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
DEV_DIR="$ROOT/.dev"
ENV_FILE="$DEV_DIR/env"
COMPOSE=(docker compose -f "$ROOT/deploy/docker-compose.dev.yml" --env-file "$ENV_FILE")

die() {
    echo "dev.sh: $*" >&2
    exit 1
}

need() {
    command -v "$1" >/dev/null 2>&1 || die "$1 is required ($2)"
}

write_env() {
    mkdir -p "$DEV_DIR/documents" "$DEV_DIR/quarantine"
    chmod 700 "$DEV_DIR"
    local port="${PERFIN_DEV_DB_PORT:-55432}" owner app
    owner="$(openssl rand -hex 16)"
    app="$(openssl rand -hex 16)"
    (
        umask 077
        cat >"$ENV_FILE" <<EOF
# Generated by scripts/dev.sh. Local development only; delete with \`make dev-reset\`.
POSTGRES_PASSWORD=$(openssl rand -hex 16)
POSTGRES_OWNER_PASSWORD=$owner
POSTGRES_APP_PASSWORD=$app
PERFIN_DEV_DB_PORT=$port
PERFIN_DEV_MODE=true
PERFIN_PUBLIC_URL=http://localhost:5173
PERFIN_SECURE_COOKIES=false
PERFIN_REQUIRE_MFA=false
PERFIN_BIND_HOST=127.0.0.1
PERFIN_BIND_PORT=8000
PERFIN_DATABASE_URL=postgresql+psycopg://perfin_app:$app@127.0.0.1:$port/perfin
PERFIN_MIGRATION_DATABASE_URL=postgresql+psycopg://perfin_owner:$owner@127.0.0.1:$port/perfin
PERFIN_DB_APP_ROLE=perfin_app
PERFIN_MASTER_KEY=$(openssl rand -base64 32)
PERFIN_SECRET_KEY=$(openssl rand -base64 48)
PERFIN_DOCUMENTS_DIR=$DEV_DIR/documents
PERFIN_QUARANTINE_DIR=$DEV_DIR/quarantine
PERFIN_BOOTSTRAP_URL_FILE=$DEV_DIR/setup-url
EOF
    )
    echo "dev.sh: generated $ENV_FILE (random passwords and keys, mode 0600)"
}

load_env() {
    [[ -f $ENV_FILE ]] || write_env
    set -a
    # shellcheck disable=SC1090
    . "$ENV_FILE"
    set +a
}

start_db() {
    need docker "https://docs.docker.com/engine/install/"
    echo "dev.sh: starting PostgreSQL (${POSTGRES_IMAGE:-docker.io/library/postgres:16-alpine})"
    "${COMPOSE[@]}" up -d --wait db \
        || die "the database did not start; behind a registry mirror set POSTGRES_IMAGE"
}

prepare() {
    need uv "https://docs.astral.sh/uv/"
    (cd "$ROOT/backend" && uv sync --quiet)
    if [[ ! -d $ROOT/frontend/node_modules ]]; then
        need npm "Node 22"
        (cd "$ROOT/frontend" && npm ci)
    fi
    (cd "$ROOT/backend" && uv run perfin migrate)
}

seed() {
    (cd "$ROOT/backend" && uv run python ../scripts/seed_dev.py)
}

up() {
    need openssl "used to generate secrets"
    load_env
    start_db
    prepare
    seed

    local pids=()
    cleanup() {
        trap - EXIT INT TERM
        echo
        echo "dev.sh: stopping (the database container keeps running; 'make dev-down' stops it)"
        local pid
        for pid in "${pids[@]}"; do
            pkill -TERM -P "$pid" 2>/dev/null || true
            kill "$pid" 2>/dev/null || true
        done
        wait 2>/dev/null || true
    }
    trap cleanup EXIT INT TERM

    # Each service's output is prefixed with its name.
    run() {
        local label="$1"
        shift
        ("$@" 2>&1 | sed -u "s/^/[$label] /") &
        pids+=("$!")
    }
    run api bash -c "cd '$ROOT/backend' && exec uv run uvicorn app.main:create_app --factory \
        --reload --reload-dir app --host '$PERFIN_BIND_HOST' --port '$PERFIN_BIND_PORT'"
    run worker bash -c "cd '$ROOT/backend' && exec uv run perfin worker"
    run web bash -c "cd '$ROOT/frontend' && exec npm run dev -- --host 127.0.0.1"
    echo
    echo "dev.sh: the PerFin dev stack is starting. Open http://localhost:5173 and sign in as"
    echo "        dev-admin (the password was printed above by the seed, once; 'make dev-reset'"
    echo "        makes a new one). API docs: http://127.0.0.1:8000/api/v1/docs. Ctrl-C stops all."
    wait
}

case "${1:-up}" in
    up)
        up
        ;;
    seed)
        load_env
        seed
        ;;
    down)
        [[ -f $ENV_FILE ]] || die "nothing to stop (no $ENV_FILE)"
        load_env
        "${COMPOSE[@]}" stop db
        ;;
    reset)
        if [[ -f $ENV_FILE ]]; then
            load_env
            "${COMPOSE[@]}" down --volumes --remove-orphans || true
        fi
        rm -rf "$DEV_DIR"
        echo "dev.sh: removed the dev database and $DEV_DIR"
        ;;
    -h | --help | help)
        sed -n '4,27p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//'
        ;;
    *)
        die "unknown command '$1' (up, seed, down, reset)"
        ;;
esac
